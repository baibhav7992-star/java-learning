package day_05.practice;
/*

Q1. Print the following pattern using nested loops:

* * *
* * *
* * *

*/
public class question_28 { public static void main(String[] args) {
    for(int i =1; i<=3;i++) {
        
        for(int j = 1; j<=3;j++) {
            System.out.println("*");
        }
    }
    System.out.println();
    
}
    
}
