package day_04.practice;
/*
Q4. Write a program to input a number from the user and print its multiplication table up to 10 using a for loop.

Example Input:
5

Output:
5 x 1 = 5
5 x 2 = 10
5 x 3 = 15
...
5 x 10 = 50
*/
public class question_04 { public static void main(String[] args) {
    for(int i = 5;i<=50;i=i+5)
    {
        System.out.println(i);
    }
}
    
}
