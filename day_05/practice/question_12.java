package day_05.practice;



/*
Q12. Write a program to count how many even numbers are present from 1 to 20.
*/
public class question_12 { public static void main(String[] args) {
    int count = 0;
    for(int i=1;i<=20;i++)
    {
        count++;
    }
    System.out.println("total count :"+count);
}
    
}
