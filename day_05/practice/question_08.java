package day_05.practice;
/*
Q8. Write a program to print the multiplication table of 5 using a for loop.

Output:
5 x 1 = 5
5 x 2 = 10
...
5 x 10 = 50
*/
public class question_08 { public static void main(String[] args) {
    for(int i=5;i<=50;i=i+5)
    {
        System.out.println(i);
    }
}
    
}
