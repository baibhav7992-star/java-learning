package day_05.practice;
/*
Q11. Write a program to print and count how many numbers are present from 1 to 10.
*/
public class question_11 { public static void main(String[] args) {
    int count = 0;
    for(int i = 1;i<=10;i++)
    {
        System.out.println(i);
        count++;
    }
    System.out.println("total count is :" +count);
}
    
}
